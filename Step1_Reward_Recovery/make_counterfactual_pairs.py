"""Create continuous kinematic expert/counterfactual preference clips for SR-AIRL.

Only complete episodes in the supplied training-split expert file are used.  A
negative is generated by integrating a sustained braking/lateral acceleration
over the whole clip, rather than editing an isolated state frame.
"""
import argparse
import pickle
import random

import torch

from reward_config import DT, HISTORY_LEN, RANK_WINDOW


def history(sequence):
    result = []
    for t in range(len(sequence)):
        start = max(0, t - HISTORY_LEN + 1)
        frames = [sequence[start]] * (HISTORY_LEN - (t - start + 1)) + [sequence[k] for k in range(start, t + 1)]
        result.append(torch.cat(frames))
    return torch.stack(result)


def perturb_clip(raw, role):
    """Integrate target acceleration in physical normalized coordinates."""
    output = raw.clone()
    target = slice(0, 4) if role == 'lcv' else slice(4, 8)
    # FV is encoded as lcv - fv, so accelerating FV changes that relative state
    # in the opposite direction.  This stays temporally continuous.
    sign = 1.0 if role == 'lcv' else -1.0
    velocity_delta = 0.0; position_delta = 0.0
    for t in range(len(output)):
        velocity_delta += -3.0 * DT / 80.0
        position_delta += velocity_delta * DT / 500.0
        if role == 'lcv':
            output[t, target.start + 1] += position_delta
            output[t, target.start + 2] += velocity_delta
        else:
            output[t, 4 + 1] -= position_delta
            output[t, 4 + 2] -= velocity_delta
        # sustained lateral acceleration creates a comfort/lane-deviation cost
        output[t, target.start + 0] += sign * 1.2 * (t * DT) ** 2 / 25.0
        output[t, target.start + 3] += sign * 2.4 * t * DT / 80.0
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--expert_path', required=True)
    parser.add_argument('--output', default='counterfactual_pairs.pt')
    parser.add_argument('--clips_per_episode', type=int, default=2)
    parser.add_argument('--seed', type=int, default=42)
    args = parser.parse_args(); random.seed(args.seed)
    with open(args.expert_path, 'rb') as file: data = pickle.load(file)
    states, dones = data['state'].float(), data['dones'].reshape(-1).bool()
    result = {role: {'positive': [], 'negative': []} for role in ('lcv', 'fv')}
    begin = 0
    # Legacy files may contain all 150 scenes.  The first 100 are the sole
    # training split; never silently draw preference pairs from validation/test.
    for episode_index, end in enumerate(torch.where(dones)[0].tolist()):
        if episode_index >= 100:
            break
        episode = states[begin:end + 1]; begin = end + 1
        if len(episode) < RANK_WINDOW: continue
        starts = random.sample(range(len(episode) - RANK_WINDOW + 1), min(args.clips_per_episode, len(episode) - RANK_WINDOW + 1))
        for start in starts:
            positive_raw = episode[start:start + RANK_WINDOW]
            for role in result:
                negative_raw = perturb_clip(positive_raw, role)
                result[role]['positive'].append(history(positive_raw))
                result[role]['negative'].append(history(negative_raw))
    for role in result:
        for kind in result[role]:
            result[role][kind] = torch.stack(result[role][kind])
    torch.save(result, args.output)
    print({role: value['positive'].shape for role, value in result.items()}, '->', args.output)


if __name__ == '__main__': main()

